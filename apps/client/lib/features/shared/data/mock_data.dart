const List<String> _seatLetters = ['A', 'B', 'C', 'D'];

SeatMap generateSeatMap(
  String tripId,
  Vehicle vehicle,
  String boardingStopId,
  String alightingStopId, [
  List<String> takenSeats = const [],
]) {
  final seats = <Seat>[];
  final taken = takenSeats.toSet();
  final cols = vehicle.layout.cols;
  final tripSeed = tripId.length > 2 ? tripId.codeUnitAt(2) : 1;
  for (var r = 1; r <= vehicle.layout.rows; r++) {
    for (var c = 0; c < cols; c++) {
      final letter = c < _seatLetters.length
          ? _seatLetters[c]
          : String.fromCharCode(65 + c);
      final number = '$r$letter';
      final seed = tripSeed * r * (c + 1);
      final isTaken = taken.contains(number);
      final pseudoTaken = !isTaken && ((seed * 7) % 11) < 4 && r > 1;
      final isBlocked = !isTaken && !pseudoTaken && r == 1 && c < 2;
      final isWindow = c == 0 || c == cols - 1;
      final isAisle = cols == 4 ? c == 1 || c == 2 : c == cols - 1;
      final position = isWindow
          ? SeatPosition.fenetre
          : isAisle
          ? SeatPosition.allee
          : SeatPosition.milieu;
      final cls = r <= 2
          ? SeatClass.vip
          : r <= 4
          ? SeatClass.confort
          : SeatClass.standard;
      final basePrice = switch (cls) {
        SeatClass.vip => 7500,
        SeatClass.confort => 6000,
        SeatClass.standard => 5000,
      };
      seats.add(
        Seat(
          id: 'seat_${tripId}_$number',
          number: number,
          row: r,
          col: c,
          seatClass: cls,
          position: position,
          status: isTaken || pseudoTaken
              ? SeatStatus.taken
              : isBlocked
              ? SeatStatus.blocked
              : SeatStatus.available,
          priceXOF: basePrice,
        ),
      );
    }
  }
  final available = seats.where((s) => s.status == SeatStatus.available).length;
  return SeatMap(
    tripId: tripId,
    vehicleId: vehicle.id,
    vehicleModel: vehicle.model,
    layout: VehicleLayout(
      rows: vehicle.layout.rows,
      cols: vehicle.layout.cols,
      hasBackRow: vehicle.layout.hasBackRow,
    ),
    seats: seats,
    boardingStopId: boardingStopId,
    alightingStopId: alightingStopId,
    availableCount: available,
    legend: const [
      SeatLegendEntry(status: SeatStatus.available, label: 'Libre'),
      SeatLegendEntry(status: SeatStatus.selected, label: 'Sélectionné'),
      SeatLegendEntry(status: SeatStatus.taken, label: 'Occupé'),
      SeatLegendEntry(status: SeatStatus.blocked, label: 'Indisponible'),
    ],
  );
}

