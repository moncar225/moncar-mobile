Trip _buildTrip(
  String id,
  Line line,
  String date,
  String departureTime,
  Vehicle vehicle,
  int priceXOF,
  int seatsTaken, {
  List<String> tags = const [],
  CancellationPolicy cancellationPolicy = CancellationPolicy.modere,
  bool direct = true,
}) {
  final co = COMPANIES.firstWhere((c) => c.id == line.companyId);
  final arrivalTime = addMinutesToTime(departureTime, line.durationRefMin);

  final fullSegment = TripSegment(
    originStopId: line.stops.first.id,
    destinationStopId: line.stops.last.id,
    originCityName: line.originCityName,
    destinationCityName: line.destinationCityName,
    departureTime: departureTime,
    arrivalTime: arrivalTime,
    durationMin: line.durationRefMin,
    priceXOF: priceXOF,
  );

  final segments = List.generate(line.stops.length - 1, (i) {
    final stop = line.stops[i];
    final next = line.stops[i + 1];
    final segPrice =
        (priceXOF * (next.minutesFromOrigin - stop.minutesFromOrigin)) ~/
        line.durationRefMin;
    return TripSegment(
      originStopId: stop.id,
      destinationStopId: next.id,
      originCityName: stop.cityName,
      destinationCityName: next.cityName,
      departureTime: addMinutesToTime(departureTime, stop.minutesFromOrigin),
      arrivalTime: addMinutesToTime(departureTime, next.minutesFromOrigin),
      durationMin: next.minutesFromOrigin - stop.minutesFromOrigin,
      priceXOF: segPrice < 1000 ? 1000 : segPrice,
    );
  });

  return Trip(
    id: id,
    lineId: line.id,
    companyId: line.companyId,
    companyName: co.name,
    companyColor: co.logoColor,
    originCityName: line.originCityName,
    destinationCityName: line.destinationCityName,
    date: date,
    departureTime: departureTime,
    arrivalTime: arrivalTime,
    durationMin: line.durationRefMin,
    distanceKm: line.distanceKm,
    vehicleId: vehicle.id,
    vehicleType: vehicle.type,
    vehicleModel: vehicle.model,
    amenities: vehicle.amenities,
    segments: [fullSegment, ...segments],
    stops: line.stops,
    seatsAvailable: vehicle.capacity - seatsTaken,
    totalSeats: vehicle.capacity,
    priceFromXOF: priceXOF,
    priceXOF: priceXOF,
    status: TripStatus.cree,
    rating: co.rating,
    reviewCount: co.reviewCount,
    direct: direct,
    cancellationPolicy: cancellationPolicy,
    tags: tags,
  );
}

