  return Line(
    id: id,
    companyId: companyId,
    companyName: co.name,
    originCityId: 'c_${originName.toLowerCase().substring(0, 3)}',
    originCityName: originName,
    destinationCityId: 'c_${destName.toLowerCase().substring(0, 3)}',
    destinationCityName: destName,
    stops: List.generate(stops.length, (i) {
      final s = stops[i];
      return Stop(
        id: '${id}_s$i',
        cityId: 'c_${s.$1.toLowerCase().substring(0, 3)}',
        cityName: s.$1,
        label: s.$2,
        latitude: s.$3,
        longitude: s.$4,
        orderInLine: i,
        minutesFromOrigin: s.$5,
      );
    }),
    distanceKm: distanceKm,
    durationRefMin: durationMin,
  );
}

