/// Location de démonstration (données cohérentes avec le devis serveur).
Rental _demoRental({
  required String id,
  required String reference,
  required RentalVehicle vehicle,
  required int startInDays,
  required int days,
  required RentalStatus status,
  required List<(String, int)> events,
  int? rating,
}) {
  final start = DateTime.now().add(Duration(days: startInDays));
  final s = DateTime(start.year, start.month, start.day, 8);
  final e = s.add(Duration(days: days));
  final brut = vehicle.pricePerDayXOF * days;
  final fees = (brut * 5 / 100).round();
  final criteria = RentalCriteria(
    pickupCity: vehicle.city,
    pickupLabel: '${vehicle.area}, ${vehicle.city}',
    area: RentalArea.interieur,
    purpose: RentalPurpose.personnel,
    persons: 2,
    start: s.toIso8601String(),
    end: e.toIso8601String(),
    durationPreset: RentalDurationPreset.plusieursJours,
    withDriver: false,
  );
  final done = status == RentalStatus.terminee;
  return Rental(
    id: id,
    reference: reference,
    vehicleId: vehicle.id,
    vehicleSummary: vehicle.summary,
    providerName: vehicle.partner,
    providerKind: vehicle.providerKind,
    criteria: criteria,
    quote: RentalQuote(
      brutLines: [
        RentalQuoteLine(
          'Location $days jours × ${vehicle.pricePerDayXOF} FCFA',
          brut,
        ),
      ],
      brutXOF: brut,
      feesXOF: fees,
      otherFees: const [RentalQuoteLine('Vérification des documents', 1000)],
      otherFeesXOF: 1000,
      totalXOF: brut + fees + 1000,
      billableLabel: '$days jours',
    ),
    status: status,
    createdAt: isoOffsetMs(events.first.$2 * 3600000),
    timeline: [
      for (final ev in events) RentalEvent(ev.$1, isoOffsetMs(ev.$2 * 3600000)),
    ],
    paymentId: done ? 'pm_demo_loc' : null,
    handoverAt: done
        ? s.add(const Duration(minutes: 17)).toIso8601String()
        : null,
    handoverLocation: done ? criteria.pickupLabel : null,
    startCondition: done
        ? VehicleCondition(
            recordedAt: s.add(const Duration(minutes: 25)).toIso8601String(),
            mileageKm: 48210,
            fuelEighths: 8,
            photos: const ['plaque', 'avant', 'arriere', 'tableau_bord'],
          )
        : null,
    returnedAt: done ? e.toIso8601String() : null,
    returnCondition: done
        ? VehicleCondition(
            recordedAt: e.toIso8601String(),
            mileageKm: 48905,
            fuelEighths: 7,
            photos: const ['avant', 'arriere', 'tableau_bord'],
            recordedBy: 'fournisseur',
          )
        : null,
    rating: rating,
  );
}

